import numpy as np
import yaml
import pandas as pd
from tqdm import tqdm
import os
from PIL import Image
import csv
import argparse

def generate_counterexample(images, masks):
    """
    Generate counterexamples for (N) images given wr masks.
    Counterexamples are generated by replacing masked regions with random values.
    
    Parameters
    ----------
    images : np.ndarray
        The images to generate counterexamples for. (N, H, W, C)
    labels : np.ndarray
        The labels for the images. (N,)
    masks : np.ndarray
        The masks for the images. (N, H, W)

    """
    masks = masks.astype(bool)[..., None]

    # Generate random values for the entire batch
    random_values = np.random.randint(0, 256, size=images.shape, dtype=np.uint8)

    # Replace masked regions with random values
    counterexamples = np.where(masks, random_values, images)

    return counterexamples


# load a dataset (including wr mask information)

def counterexamples(dataset_name, augmented_dir):
    with open(
        f"data/datasets_info.yaml", "r"
    ) as file:
        dataset_yaml = yaml.safe_load(file)
    # set raw and gt paths
    raw_dir = dataset_yaml[dataset_name]["raw_dir"]
    wr_masks_dir = dataset_yaml[dataset_name]["wr_masks_dir"]
    # get gt metadata
    gt_label_path = dataset_yaml[dataset_name]["gt_label_path"]
    metadata = pd.read_csv(gt_label_path)
    augmented_csv_info = []

    
    # load and modify dataset
    for i, row in tqdm(metadata.iterrows()):
        # check whether the example contains a shortcut and is in the training set
        if int(row["confounder_label"]) == 0:
            continue
        if row["split"]  != 0:
            continue

        # get paths
        raw_img_path = os.path.join(raw_dir, row["filename"])
        wr_mask_path = os.path.join(wr_masks_dir, row["filename"])

        # load images and masks
        image = Image.open(raw_img_path).convert("RGB")
        image = np.array(image.resize((299, 299), resample=Image.LANCZOS))
        if os.path.exists(wr_mask_path):
            if not dataset_name == "ISIC19":
                wr_mask = Image.open(wr_mask_path).convert("L").point(lambda x: 0 if x < 128 else 255)
                wr_mask = np.array(wr_mask.resize((299, 299), resample=Image.LANCZOS))
            else:
                wr_mask = np.array(Image.open(wr_mask_path).convert("L").point(lambda x: 0 if x < 128 else 255))
        else:
            continue  # we cannot generate counterexamples without wr masks

        # generate counterexamples
        new_img = generate_counterexample(image, wr_mask)
        
        # save the new img
        new_filename = f"{row['filename'][:-4]}_ce.jpg"
        new_img_path = os.path.join(augmented_dir, new_filename)
        Image.fromarray(new_img).save(new_img_path)
        augmented_csv_info.append({'filename': new_filename, 'class_label': row['class_label'], 'confounder_label': 0, 'split': 0})

    with open(os.path.join(augmented_dir, "gt_labels.csv"), mode="w", newline="") as file:
        fieldnames = ["filename", "class_label", "confounder_label", "split"]  # Column headers
        writer = csv.DictWriter(file, fieldnames=fieldnames)

        writer.writeheader()  # Write column names
        writer.writerows(augmented_csv_info)  # Write data


if __name__ == "__main__":
    # Set up argument parser
    parser = argparse.ArgumentParser(description="Create CAIPI counterexamples for a dataset")
    parser.add_argument("--dataset_name", type=str, help="Name of the dataset config")
    parser.add_argument("--augmented_dir", type=str, help="Path to the augmented directory")

    args = parser.parse_args()

    counterexamples(args.dataset_name, args.augmented_dir)